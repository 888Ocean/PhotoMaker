/* Optional UI integration check. Requires Playwright and Chrome; uses an isolated test server. */
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1050}, deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const preview=process.argv.includes('--preview');
  const base=preview?'http://127.0.0.1:4317':process.env.PHOTOMAKER_TEST_URL || 'http://127.0.0.1:4318';
  const waitFor = async (predicate, timeout=10000) => {
    const start=Date.now();while(Date.now()-start<timeout){if(await predicate())return;await page.waitForTimeout(100);}throw new Error('Condition timed out');
  };
  const action = name => page.locator(`[data-action="${name}"]`);
  const tab = name => page.locator(`[data-action="tab"][data-id="${name}"]`);
  const readProject=async()=>page.evaluate(async()=>{const id=location.hash.split('/')[2];return fetch('/api/projects/'+id).then(r=>r.json());});
  try {
    if(preview){
      const existing=await (await page.request.get(base+'/api/projects')).json();
      if(!existing.length)await page.request.post(base+'/api/sample',{data:{}});
      await page.goto(base);
      await page.locator('.project-card').first().waitFor();
      await page.locator('.hero-art img').first().evaluate(img=>img.decode());
      await page.screenshot({path:path.resolve(__dirname,'../test-results/workspace-preview.png'),fullPage:true});
      console.log('Preview ready at '+base);return;
    }
    const health=await (await page.request.get(base+'/api/health')).json();
    assert(health.data_dir.includes('/photomaker-browser.'),'Run UI tests only against a separate temporary data directory.');
    const previous=await (await page.request.get(base+'/api/projects')).json();
    for(const project of previous)await page.request.patch(base+'/api/projects/'+project.id,{data:{archived:true}});
    await page.request.post(base+'/api/settings',{data:{ai_base_url:'',ai_model:'',ai_api_key:'',comfy_url:'',ai_vision:false}});
    await page.goto(base);
    await page.getByRole('heading',{name:'你的照片，下一段故事。'}).waitFor();
    assert.equal(await page.locator('.project-card').count(),0);
    await action('sample').click();
    await page.locator('.asset-card').first().waitFor();
    assert.equal(await page.locator('.asset-card').count(),4);
    const projectId=(await readProject()).id;
    assert.equal(await page.locator('.director-panel [name=platforms]').count(),7);
    await page.locator('.director-panel [value=instagram]').check();
    await waitFor(async()=>(await readProject()).platforms.includes('instagram'));
    assert((await page.locator('#platform-summary').textContent()).includes('Instagram'));
    await page.locator('.director-panel [value=instagram]').uncheck();
    await waitFor(async()=>(await readProject()).platforms.length===1);
    await action('save-version').first().click();
    await page.locator('#version-form [name=label]').fill('浏览器验证快照');
    await page.locator('#version-form [type=submit]').click();
    await waitFor(async()=>!(await page.locator('#modal').evaluate(el=>el.open)));
    await tab('story').click();
    await page.locator('#story-title').fill('海风与微光');
    await page.locator('#story-body').fill('这是一条用于验证自动保存的真实编辑。');
    await waitFor(async()=>(await readProject()).story.title==='海风与微光');
    assert.equal(await page.locator('#story-preview-title').textContent(),'海风与微光');
    await tab('photos').click();
    await action('toggle-photo').nth(1).click();
    await action('move-left').nth(3).click();
    await waitFor(async()=>(await readProject()).assets.filter(a=>a.selected).length===3);
    await action('plan-local').click();
    await waitFor(async()=>(await readProject()).versions.some(v=>v.source==='local'));
    await waitFor(async()=>(await page.locator('#job-log').textContent()).includes('已完成'));
    await tab('versions').click();
    const original=(await readProject()).versions[0];
    await page.locator(`[data-action="restore-version"][data-id="${original.id}"]`).click();
    await waitFor(async()=>(await readProject()).versions.some(v=>v.source==='restore'));
    assert.equal((await readProject()).story.title,'潮汐的注脚');
    await tab('photos').click();
    const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=240;c.height=300;const ctx=c.getContext('2d');ctx.fillStyle='#456b81';ctx.fillRect(0,0,240,300);ctx.fillStyle='#e6d9b9';ctx.fillRect(0,230,240,70);return c.toDataURL('image/png').split(',')[1];});
    const file={name:'browser-import.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')};
    await page.locator('#file-input').setInputFiles(file);
    await waitFor(async()=>(await readProject()).assets.length===5);
    await waitFor(async()=>!(await page.locator('#main').evaluate(el=>el.inert)));
    await page.locator('#file-input').setInputFiles(file);
    await waitFor(async()=>(await page.locator('#toast').textContent()).includes('跳过 1 张'));
    assert.equal((await readProject()).assets.length,5);
    const asset=(await readProject()).assets.find(a=>a.name==='browser-import.png');
    assert.equal(asset.features.width,240);
    assert.equal(asset.features.height,300);
    assert(asset.features.palette.length>0 && asset.features.palette.length<=5);
    await tab('versions').click();
    await page.locator(`[data-action="restore-version"][data-id="${original.id}"]`).click();
    await waitFor(async()=>(await readProject()).assets.find(a=>a.id===asset.id)?.selected===false);
    assert.equal((await readProject()).assets.length,5);
    const downloadPromise=page.waitForEvent('download');
    await action('export').click();
    const download=await downloadPromise;
    const out=path.resolve(__dirname,'../test-results');fs.mkdirSync(out,{recursive:true});
    await download.saveAs(path.join(out,'browser-export.zip'));
    assert((await fs.promises.stat(path.join(out,'browser-export.zip'))).size>1000);
    await tab('publish').click();
    await action('publish').click();
    await page.locator('#publish-form [name=url]').fill('https://example.com/test-publication');
    await page.locator('#publish-form [name=feedback]').fill('浏览器流程测试，非真实平台发布。');
    await page.locator('#publish-form [type=submit]').click();
    await waitFor(async()=>(await readProject()).publications.length===1);
    await page.locator('[data-feedback]').fill('后续测试反馈');
    await page.locator('[data-feedback]').blur();
    await waitFor(async()=>(await readProject()).publications[0].feedback==='后续测试反馈');
    await page.locator('a[href="#/styles"]').first().click();
    await action('new-recipe').first().click();
    await page.locator('#recipe-form [name=name]').fill('测试蓝调配方');
    await page.locator('#recipe-form [name=description]').fill('适合海边照片的轻柔蓝调');
    await page.locator('#recipe-form [name=positive_prompt]').fill('muted ocean blue');
    await page.locator('#recipe-form [type=submit]').click();
    await page.locator('.recipe-card').first().waitFor();
    await page.goto(base+'/#/project/'+projectId);
    await page.locator('#project-recipe').waitFor();
    await page.locator('#project-recipe').selectOption({label:'测试蓝调配方'});
    await waitFor(async()=>!!(await readProject()).recipe_id);
    await page.locator('a[href="#/settings"]').last().click();
    await page.locator('.integration-item').first().waitFor();
    assert.equal(await page.locator('.integration-item').count(),7);
    assert.equal(await page.locator('.integration-item').filter({hasText:'账号直发：未连接'}).count(),7);
    assert.equal((await page.request.get(base+'/platforms.css')).status(),200);
    await page.screenshot({path:path.resolve(__dirname,'../test-results/platforms-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.resolve(__dirname,'../test-results/platforms-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Platforms mobile overflow');
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('[name=ai_base_url]').fill('http://127.0.0.1:9/v1');
    await page.locator('[name=ai_model]').fill('unreachable-test-model');
    await page.locator('#settings-form [type=submit]').click();
    await page.locator('.settings-card-head .badge').filter({hasText:'已配置'}).waitFor();
    await page.goto(base+'/#/project/'+projectId);
    await action('plan-ai').waitFor();
    await action('plan-ai').click();
    await waitFor(async()=>(await page.locator('#job-log').textContent()).includes('失败'));
    assert.equal((await readProject()).story.title,'潮汐的注脚');
    await page.goto(base+'/#/library');
    await page.locator('.project-card').waitFor();
    await page.screenshot({path:path.join(out,'library-desktop.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'library-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Library mobile overflow');
    await page.goto(base+'/#/project/'+projectId);
    await page.locator('.asset-card').first().waitFor();
    await page.screenshot({path:path.join(out,'project-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Project mobile overflow');
    await page.setViewportSize({width:1440,height:1050});
    await page.screenshot({path:path.join(out,'project-desktop.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: import, dedup, autosave, ordering, local task, snapshot restore, original retention, export, publication, feedback, style reuse, upstream error, desktop/mobile layout; no browser exceptions.');
  } catch(error) {
    const out=path.resolve(__dirname,'../test-results');fs.mkdirSync(out,{recursive:true});
    await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});
    throw error;
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
